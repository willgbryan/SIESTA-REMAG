"""Correspondence of saved native meshes without changing sampled spectra.

The fallback is specific to prepared diagonal, undisplaced Monkhorst-Pack
meshes. It proves unique grid labels using the original KP printing intervals,
input cell and the two length conventions supported by pinned SIESTA 5.4.
It never snaps coordinates, resamples states or assigns an energy error bound.
"""
from decimal import Decimal, InvalidOperation
from pathlib import Path
import re

import numpy as np

from ..corpus import sha256
from ..discovery.common import digest

# Pinned upstream Src/libunits/{units_codata2018,units_legacy}.f90.
# A convention is admitted only if it reproduces the stored fractional arrays.
BOHR_ANGSTROM = {'codata2018': .529177210903, 'legacy': .529177}


def native_report_context(endpoint,metadata):
    """Admit optional native context for a standalone spectral comparison."""
    from .tools import _verified_report
    if (not isinstance(endpoint,dict) or not {'report','stage'}<=set(endpoint)
            or set(endpoint)-{'report','stage','collection'} or not isinstance(endpoint['stage'],str)
            or not re.fullmatch(r'scalar|soc-[a-z][a-z0-9_-]{0,31}',endpoint['stage'])):
        raise ValueError('Native spectral context requires report, stage and optional collection')
    path=Path(endpoint['report']).resolve();stage=endpoint['stage']
    report=_verified_report(path,Path(endpoint['collection']).resolve() if 'collection' in endpoint else None)
    if report['status']!='measured' or not any(s['stage']==stage and s['accepted'] and s.get('branch',{}).get('passed',True) for s in report['stages']):
        raise ValueError('Native spectral context stage has not passed')
    for suffix,key in [('HSX','hsx_sha256'),('KP','kp_sha256'),('EIG','eig_sha256')]:
        expected=report['artifacts'].get(stage+'/remag.'+suffix)
        if not expected or metadata.get(key)!=expected:raise ValueError('Spectrum differs from its native context stage')
    return dict(report_path=path,report=report,metadata=metadata,stage=stage,
        binding=dict(report_sha256=sha256(path),source_sha256=report['source_sha256'],stage=stage,verification=report['verification']))


def _tokens(tokens):
    try:
        values=[Decimal(x.replace('D','E').replace('d','e')) for x in tokens]
    except (InvalidOperation,ValueError):
        raise ValueError('Invalid native KP number') from None
    if any(not v.is_finite() or abs(v.as_tuple().exponent)>100 for v in values):
        raise ValueError('Invalid native KP number or precision')
    return np.array([float(v) for v in values]), np.array([float(Decimal(10)**v.as_tuple().exponent/2) for v in values])


def _bound_file(context,name,limit):
    root=Path(context['report_path']).resolve().parent
    relative=context['stage']+'/'+name;path=(root/relative).resolve()
    expected=context['report']['artifacts'].get(relative)
    if (not path.is_relative_to(root) or not expected or not path.is_file()
            or path.stat().st_size>limit or sha256(path)!=expected):
        raise ValueError('Native sampling requires the original bound '+name)
    return path


def _input_cell(text,mesh):
    """Read the explicit input form generated by discovery.inputs only."""
    normalize=lambda x:re.sub(r'[._-]','',x).lower()
    blocks={};values={};active=None
    for line in text.splitlines():
        tokens=re.split(r'[#!]',line,maxsplit=1)[0].split()
        if not tokens:continue
        if '<' in tokens or tokens[0].lower()=='%include':raise ValueError('Indirect sampling input is unsupported')
        if tokens[0].lower()=='%block':
            if active is not None or len(tokens)!=2:raise ValueError('Invalid sampling input block')
            active=normalize(tokens[1])
            if active in blocks:raise ValueError('Duplicate sampling input block')
            blocks[active]=[]
        elif tokens[0].lower()=='%endblock':
            if active is None or (len(tokens)>1 and normalize(tokens[1])!=active):raise ValueError('Unmatched sampling input block')
            active=None
        elif active is not None:blocks[active].append(tokens)
        else:
            key=normalize(tokens[0])
            if key in values:raise ValueError('Duplicate sampling input setting')
            values[key]=tokens[1:]
    if active is not None:raise ValueError('Incomplete sampling input block')
    lc=values.get('latticeconstant',[])
    if len(lc)!=2 or lc[1].lower() not in ('ang','angstrom') or _tokens(lc[:1])[0][0]!=1:
        raise ValueError('Sampling correspondence requires explicit LatticeConstant 1 Ang')
    cell_rows=blocks.get('latticevectors',[]);grid_rows=blocks.get('kgridmonkhorstpack',[])
    if len(cell_rows)!=3 or any(len(r)!=3 for r in cell_rows) or len(grid_rows)!=3 or any(len(r)!=4 for r in grid_rows):
        raise ValueError('Explicit cell and Monkhorst-Pack input blocks required')
    cell=_tokens([v for row in cell_rows for v in row])[0].reshape(3,3)
    grid=_tokens([v for row in grid_rows for v in row])[0].reshape(3,4)
    if not np.array_equal(grid[:,:3],np.diag(mesh)) or np.any(grid[:,3]!=0):
        raise ValueError('Sampling correspondence supports the declared diagonal zero-displacement mesh only')
    determinant=np.linalg.det(cell)
    if not np.isfinite(cell).all() or not np.isfinite(determinant) or determinant<=0:raise ValueError('Invalid native sampling cell')
    return cell


def native_mesh_identity(arrays,context):
    """Bind every stored sample to one uniquely resolved declared mesh point."""
    report=context['report'];mesh=report['request']['kmesh']
    if (report['request'].get('fixed_geometry') is not True or not isinstance(mesh,list) or len(mesh)!=3
            or any(type(n) is not int or not 1<=n<=1024 for n in mesh) or np.prod(mesh)>100000):
        raise ValueError('Native sampling needs a fixed geometry and a bounded explicit mesh')
    mesh=np.array(mesh,dtype=np.int64);size=int(np.prod(mesh))
    kp=_bound_file(context,'remag.KP',32*1024*1024)
    inp=_bound_file(context,'input.fdf',1024*1024)
    cell=_input_cell(inp.read_text(),mesh)
    authored=np.asarray(report['structure']['geometry']['cell'],float)
    if authored.shape!=(3,3) or not np.allclose(cell,authored,rtol=0,atol=1e-12):
        raise ValueError('Native sampling input cell differs from the fixed authored geometry')
    if context['metadata'].get('kp_sha256')!=sha256(kp):raise ValueError('Spectrum native KP binding differs')
    lines=kp.read_text().splitlines()
    try:count=int(lines[0])
    except (ValueError,IndexError):raise ValueError('Invalid native KP count') from None
    rows=[line.split() for line in lines[1:]]
    if not 1<=count<=size or len(rows)!=count or any(len(row)!=5 for row in rows):raise ValueError('Invalid native KP dimensions')
    try:indices=[int(row[0]) for row in rows]
    except ValueError:raise ValueError('Invalid native KP indices') from None
    if indices!=list(range(1,count+1)):raise ValueError('Native KP ordering is incomplete')
    values,half=_tokens([v for row in rows for v in row[1:]])
    values=values.reshape(count,4);half=half.reshape(count,4)
    ks,ws=arrays['k_fractional'],arrays['k_weights']
    if ks.shape!=(count,3) or ws.shape!=(count,) or not np.isfinite(ks).all() or not np.isfinite(ws).all():
        raise ValueError('Saved spectrum omits or adds native KP samples')
    from .electronic import _native_weights
    normalized,total,weight_bound=_native_weights([row[4] for row in rows])
    if not np.allclose(ws,normalized,rtol=0,atol=1e-12):raise ValueError('Saved spectrum weights differ from native KP')
    multiplicities=np.rint(values[:,3]*size).astype(np.int64)
    if (np.any(multiplicities<1) or multiplicities.sum()!=size
            or np.any(abs(values[:,3]-multiplicities/size)>half[:,3]+64*np.finfo(float).eps)):
        raise ValueError('Native weights are not complete mesh multiplicities within printed precision')
    admitted=[];identities=[]
    cart=values[:,:3];cart_half=half[:,:3]
    for label,bohr in BOHR_ANGSTROM.items():
        transform=(cell/bohr).T/(2*np.pi)
        fractional=cart@transform
        # This is only a floating arithmetic reproducibility check, separate
        # from the native decimal printing intervals used below.
        arithmetic=64*np.finfo(float).eps*max(1.,float(np.max(abs(cart)))*float(np.linalg.norm(transform,ord=1)))
        if not np.isfinite(fractional).all() or not np.isfinite(arithmetic):continue
        if not np.allclose(fractional,ks,rtol=0,atol=arithmetic):continue
        bounds=cart_half@abs(transform)+arithmetic
        if np.any(bounds*mesh>=.5):continue  # More than one grid label could fit.
        labels=np.rint(fractional*mesh).astype(np.int64)
        if np.any(abs(fractional-labels/mesh)>bounds):continue
        try:
            expected_cart=(labels/mesh)@np.linalg.inv(transform)
            condition=float(np.linalg.cond(transform))
        except np.linalg.LinAlgError:continue
        cart_arithmetic=64*np.finfo(float).eps*condition*max(1.,float(np.max(abs(expected_cart))),float(np.max(abs(cart))))
        # An unstable conversion must not enlarge a printing interval enough
        # to decide correspondence. Require the roundoff allowance to be tiny
        # relative to every recorded Cartesian last-place unit.
        if (not np.isfinite(expected_cart).all() or not np.isfinite(cart_arithmetic)
                or cart_arithmetic>.01*float(cart_half.min())):continue
        if np.any(abs(cart-expected_cart)>cart_half+cart_arithmetic):continue
        canonical=labels % mesh
        if len({tuple(row) for row in canonical})!=count:continue
        identities.append(canonical)
        admitted.append(dict(length_convention=label,bohr_angstrom=bohr,
            maximum_fractional_printing_bound=float(bounds.max()),maximum_fractional_mesh_residual=float(abs(fractional-labels/mesh).max()),
            array_reproduction_roundoff_bound=arithmetic,cartesian_conversion_roundoff_allowance=cart_arithmetic))
    if not admitted:raise ValueError('Native coordinates do not identify unique declared mesh points within KP printed precision')
    if any(not np.array_equal(identity,identities[0]) for identity in identities[1:]):raise ValueError('Ambiguous native mesh correspondence')
    identity=dict(mesh=mesh.tolist(),ordered_grid_indices=identities[0].tolist(),multiplicities=multiplicities.tolist())
    proof=dict(input_sha256=sha256(inp),kp_sha256=sha256(kp),native_sample_count=count,full_mesh_size=size,
        represented_weight_sum=total,native_weight_printing_bound=weight_bound,
        identity_sha256=digest(identity),admitted_length_conventions=admitted,
        scope='All stored native samples uniquely labeled on the declared mesh; symmetry multiplicities retained; no coordinate/state resampling')
    return identity,proof


def compare_sampling(first,second,first_context=None,second_context=None):
    """Preserve strict literal matching; use bound native proof only if needed."""
    if all(first[k].shape==second[k].shape and np.allclose(first[k],second[k],rtol=0,atol=1e-12)
           for k in ('k_fractional','k_weights')):
        return dict(mode='literal_ordered_arrays',absolute_tolerance=1e-12,coordinates_modified=False)
    if first_context is None or second_context is None:raise ValueError('Response spectral sampling differs; native context unavailable')
    try:
        a,pa=native_mesh_identity(first,first_context);b,pb=native_mesh_identity(second,second_context)
    except ValueError as exc:
        raise ValueError('Response spectral sampling differs: '+str(exc)) from exc
    if a!=b:raise ValueError('Response spectral sampling differs in ordered mesh points or multiplicities')
    ca={r['length_convention'] for r in pa['admitted_length_conventions']}
    cb={r['length_convention'] for r in pb['admitted_length_conventions']}
    if not ca&cb:raise ValueError('Response native length conventions differ')
    return dict(mode='native_KP_printing_intervals',before=pa,after=pb,common_length_conventions=sorted(ca&cb),
        maximum_stored_fractional_difference=float(abs(first['k_fractional']-second['k_fractional']).max()),
        coordinates_modified=False,states_interpolated=False,
        energy_error_bound=None,scope='Sampling correspondence only; printed-coordinate effects on spectra and response accuracy remain unbounded')
